// =====================
// 游戏配置层 · 类型
//
// 背景（代码审计 A3）：产品主张是「面向校园乃至第三方个体赛事，涵盖主流游戏」，
// 但地图目录、段位阶梯、擅长位置、队伍规模、识图用的游戏标识全都写死成《无畏契约》；
// 赛事级那个 `game` 字段不驱动上面任何一处。这一层把它们收成**一款游戏一份配置**，
// 让赛程、报名、BP、识图都从配置取值 —— 加一款游戏 = 加一份配置。
//
// ★ 本层的边界（写下来避免误解）：
//   · 负责：一款游戏**有哪些**地图 / 段位 / 位置 / 人数 / 识图标识。
//   · 暂不负责：「本场赛事是**哪一款**游戏」。赛事级的 `game` 字段仍是自由文本，
//     选择逻辑还没接上，见 `games/index.ts` 里 `getGameConfig` 的说明。
//     换句话说——**数据已经统一了，选择还没有**。这是有意分两步做：
//     第一步不改变任何行为（便于验证），第二步才让 `game` 真正驱动取值。
// =====================

/** 一张地图。`name` 是中文显示名，`codeName` 是官方英文名（人工核对与模型提示时用）。 */
export interface GameMap {
  id: string;
  name: string;
  codeName: string;
  image: string;
}

/** 队伍规模约束。冻结满编、确认名单等动作都以它为准。 */
export interface GameRosterLimits {
  /** 首发人数。 */
  starters: number;
  /** 替补上限。 */
  maxSubstitutes: number;
  /** 教练上限。 */
  maxCoaches: number;
}

/** 一款游戏的完整配置。 */
export interface GameConfig {
  /** 稳定标识。**存量数据与代码引用它，不要改**（改了要一起迁移）。 */
  id: string;
  /** 展示名（中文）。 */
  displayName: string;
  /**
   * 识图提示词里用的英文游戏标识。
   *
   * 刻意与 `id` 分成两个字段：`id` 面向代码与存量数据，改它会牵动数据迁移；
   * 而这个是喂给视觉模型的提示词片段，将来换模型 / 改提示词时可能需要单独调整。
   */
  visionGameId: string;
  /**
   * 赛事配置 `game` 字段里可能出现的其他写法（中文显示名、英文名等）。
   *
   * 存在的理由：`game` 是**自由文本**（赛事创建表单里可以直接输入），
   * 而历届赛事填的是「无畏契约」这种显示名，不是 `id`。
   * 没有别名表，`getGameConfig(event.game)` 就认不出自家游戏、静默退回默认款 ——
   * 那会让「按赛事选游戏」看起来生效了、其实没生效。
   */
  aliases: string[];
  /** 完整地图目录。赛事从它里面挑图池。 */
  maps: GameMap[];
  /** 默认图池：新建赛事时预勾选的地图。 */
  defaultMapPool: Array<{ id: string; name: string }>;
  /**
   * 段位阶梯，**由低到高**。
   *
   * 数值不再单独维护一张对照表，而是「下标 + 1」派生（见 `rankValueOf`）——
   * 原来段位名在 3 个地方各写了一遍，加一档要改 3 处，早晚会漏。
   */
  ranks: string[];
  /** 选手擅长位置（多选）。数组顺序即界面上的排列顺序。 */
  positions: string[];
  /** 队伍规模约束。 */
  roster: GameRosterLimits;
  /**
   * 默认 BP 顺序（ban / pick 序列）。
   *
   * ⚠️ 目前**全仓库没有调用点**（从 `maps.ts` 原样搬过来，注释写的是「兼容旧数据」）。
   * 保留是因为它是游戏属性、且属于已交付的行为面；如需精简，它是一个明确的删除候选。
   */
  defaultBpOrder: Array<"ban" | "pick">;
}
